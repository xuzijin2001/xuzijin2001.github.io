  var STORAGE_KEY = "beea-lang";

  function detect() {
    var q = new URLSearchParams(window.location.search).get("lang");
    if (q && DICT[q]) return q;
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved && DICT[saved]) return saved;
    } catch (e) { /* storage blocked — fall through */ }
    var nav = (navigator.language || "en").toLowerCase();
    if (nav.indexOf("zh") === 0) return "zh";
    if (nav.indexOf("es") === 0) return "es";
    return "en";
  }

  function apply(lang) {
    var dict = DICT[lang] || DICT.en;
    var fallback = DICT.en;

    function t(key) {
      return dict[key] || fallback[key] || null;
    }

    document.documentElement.setAttribute("lang", LANGS[lang].htmlLang);

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var v = t(el.getAttribute("data-i18n"));
      if (v !== null) el.textContent = v;
    });
    document.querySelectorAll("[data-i18n-content]").forEach(function (el) {
      var v = t(el.getAttribute("data-i18n-content"));
      if (v !== null) el.setAttribute("content", v);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var v = t(el.getAttribute("data-i18n-placeholder"));
      if (v !== null) el.setAttribute("placeholder", v);
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach(function (el) {
      var v = t(el.getAttribute("data-i18n-aria-label"));
      if (v !== null) el.setAttribute("aria-label", v);
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      var v = t(el.getAttribute("data-i18n-alt"));
      if (v !== null) el.setAttribute("alt", v);
    });

    // the footer year is written by script.js, so restore it after a swap
    document.querySelectorAll("[data-year]").forEach(function (el) {
      el.textContent = new Date().getFullYear();
    });

    // reflect state in the switcher
    document.querySelectorAll(".lang-current").forEach(function (el) {
      el.textContent = LANGS[lang].short;
    });
    document.querySelectorAll(".lang-menu [data-lang]").forEach(function (btn) {
      btn.setAttribute("aria-current", btn.getAttribute("data-lang") === lang ? "true" : "false");
    });

    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    window.BEEA_LANG = lang;
  }

  function wire() {
    var wrap = document.querySelector(".lang-switch");
    if (!wrap) return;
    var toggle = wrap.querySelector(".lang-btn");
    var menu = wrap.querySelector(".lang-menu");

    function close() {
      wrap.classList.remove("open");
      toggle.setAttribute("aria-expanded", "false");
    }

    toggle.addEventListener("click", function (e) {
      e.stopPropagation();
      var open = wrap.classList.toggle("open");
      toggle.setAttribute("aria-expanded", open ? "true" : "false");
    });

    menu.querySelectorAll("[data-lang]").forEach(function (btn) {
      btn.addEventListener("click", function () {
        apply(btn.getAttribute("data-lang"));
        close();
      });
    });

    document.addEventListener("click", function (e) {
      if (!wrap.contains(e.target)) close();
    });
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape") close();
    });
  }

  function init() {
    apply(detect());
    wire();
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
